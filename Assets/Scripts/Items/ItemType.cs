using UnityEngine;

/// <summary>
/// Enum định nghĩa các loại vật phẩm trong game
/// </summary>
public enum ItemType
{
    Resource,    // Tài nguyên (đá, gỗ, quặng)
    Tool,        // Công cụ (búa, rìu, cuốc)
    Consumable,  // Vật phẩm tiêu hao (thức ăn, thuốc)
    Weapon,      // Vũ khí
    Material     // Nguyên liệu chế tạo
}
